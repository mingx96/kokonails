// Optional check: use an already installed Playwright runtime. Never installs or
// attaches to an existing browser. Start the local static server separately.
const playwrightModule = process.env.KOKO_PLAYWRIGHT_MODULE || 'playwright';
const { chromium } = require(playwrightModule);
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const crypto = require('node:crypto');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'output', 'playwright');
const sourceFiles = ['public/index.html','public/styles.css','public/app.mjs','public/booking.mjs','scripts/serve.mjs','scripts/build.mjs','vercel.json','tests/browser-boot.cjs','tests/browser-flow.cjs'];
const target = new URL(process.env.KOKO_BASE_URL || 'http://127.0.0.1:4173');
assert.ok(['http:','https:'].includes(target.protocol) && ['127.0.0.1','[::1]'].includes(target.hostname) &&
  !target.username && !target.password && target.pathname === '/' && !target.search && !target.hash,
  'KOKO_BASE_URL must be a loopback IP origin, with no credentials, path, query or fragment');
const base = target.origin;
const future = new Date(Date.now() + 2*24*60*60*1000).toISOString().slice(0,10);
const nextFuture = new Date(Date.now() + 3*24*60*60*1000).toISOString().slice(0,10);
const results = [];

(async()=>{
  const testedCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
  if (process.env.KOKO_EXPECTED_COMMIT) assert.equal(testedCommit,process.env.KOKO_EXPECTED_COMMIT);
  await fs.mkdir(output,{recursive:true});
  const sources = Object.fromEntries(await Promise.all(sourceFiles.map(async p=>[p,crypto.createHash('sha256').update(await fs.readFile(path.join(root,p))).digest('hex')])));
  const launch = {headless:true};
  if (process.env.KOKO_CHROMIUM_EXECUTABLE) launch.executablePath = process.env.KOKO_CHROMIUM_EXECUTABLE;
  const browser = await chromium.launch(launch);
  try {
    for (const width of [390,768,1440]) {
      const context = await browser.newContext({viewport:{width,height:width===390?844:1000},reducedMotion:'reduce'});
      await context.route('**/*',route=>new URL(route.request().url()).origin===base ? route.continue() : route.abort('blockedbyclient'));
      const page = await context.newPage();
      const requests=[], errors=[], consoleErrors=[];
      page.on('request', r=>requests.push({url:r.url(),method:r.method()}));
      page.on('pageerror',e=>errors.push(e.message));
      page.on('console',m=>{if(m.type()==='error') consoleErrors.push(m.text());});
      const response = await page.goto(base,{waitUntil:'networkidle'});
      assert.equal(response.status(),200);
      assert.match(response.headers()['x-robots-tag'],/noindex/);
      await fs.writeFile(path.join(output,`snapshot-${width}.yml`),await page.locator('body').ariaSnapshot());
      assert.equal(await page.locator('html').getAttribute('lang'),'de');
      assert.match(await page.locator('meta[name="robots"]').getAttribute('content'),/noindex,nofollow/);
      const bodyText = await page.locator('body').innerText();
      assert.ok(!bodyText.includes('\uFFFD'),'UTF-8 text contains replacement characters');
      assert.match(bodyText,/erfundenen Beispieldaten/);
      assert.equal(await page.locator('input[type="email"],input[type="tel"],textarea').count(),0);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,`overflow at ${width}`);
      await page.screenshot({path:path.join(output,`layout-${width}.png`),fullPage:true});
      await page.keyboard.press('Tab');
      assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('href')),'#main');
      await page.locator('#booking-form button[type="submit"]').click();
      assert.equal(await page.evaluate(()=>document.activeElement.id),'location');
      await page.locator('#location').selectOption('demo-a');
      await page.locator('input[name="serviceId"][value="demo-care"]').check();
      await page.locator('#date').fill(future);
      await page.locator('#time').fill('14:30');
      await page.locator('#booking-form input[name="privacyAccepted"]').check();
      await page.locator('#booking-form button[type="submit"]').click();
      assert.equal(await page.locator('#receipt').isVisible(),true);
      assert.match(await page.locator('#receipt').innerText(),/PENDING/);
      assert.match(await page.locator('#receipt').innerText(),/kein Termin reserviert/);
      assert.equal(await page.evaluate(()=>document.activeElement.id),'receipt');
      await page.locator('#booking-form button[type="submit"]').click();
      assert.equal(await page.locator('#queue .queue-item').count(),0);
      await page.locator('#demo-role').selectOption('staff-demo');
      assert.equal(await page.locator('#queue .queue-item').count(),1,'idempotent double submission');
      await page.locator('input[name="serviceId"][value="demo-colour"]').check();
      await page.locator('#booking-form button[type="submit"]').click();
      assert.match(await page.locator('#form-error').innerText(),/schon eine offene oder/);
      assert.equal(await page.evaluate(()=>document.activeElement.id),'form-error');
      assert.equal(await page.locator('#queue .queue-item').count(),1,'duplicate with a changed service rejected');
      await page.locator('input[name="serviceId"][value="demo-care"]').check();
      const item = page.locator('#queue .queue-item').first();
      await item.locator('button[type="submit"]').click();
      assert.equal(await item.locator('input[name="treatwellReference"]').evaluate(e=>e.validity.valueMissing),true);
      await item.locator('input[name="treatwellReference"]').fill('DEMO-X');
      await item.locator('button[type="submit"]').click();
      assert.equal(await item.locator('input[name="treatwellReference"]').evaluate(e=>e.validity.patternMismatch),true);
      await item.locator('input[name="treatwellReference"]').fill('DEMO-QA123');
      await item.locator('button[type="submit"]').click();
      assert.equal(await item.locator('input[name="manuallyChecked"]').evaluate(e=>e.validity.valueMissing),true);
      await item.locator('input[name="manuallyChecked"]').check();
      await item.locator('select[name="matchedLocationId"]').selectOption('demo-b');
      await item.locator('button[type="submit"]').click();
      assert.match(await item.locator('[role="alert"]').innerText(),/genau zur Anfrage passen/);
      assert.equal(await item.locator('[role="alert"]').evaluate(e=>e===document.activeElement),true);
      await item.locator('select[name="matchedLocationId"]').selectOption('demo-a');
      await item.locator('input[name="matchedDate"]').fill(nextFuture);
      await item.locator('button[type="submit"]').click();
      assert.match(await item.locator('[role="alert"]').innerText(),/genau zur Anfrage passen/);
      await item.locator('input[name="matchedDate"]').fill(future);
      await item.locator('input[name="matchedTime"]').fill('14:31');
      await item.locator('button[type="submit"]').click();
      assert.match(await item.locator('[role="alert"]').innerText(),/genau zur Anfrage passen/);
      await item.locator('input[name="matchedTime"]').fill('14:30');
      await item.locator('button[type="submit"]').click();
      assert.match(await page.locator('#queue').innerText(),/CONFIRMED/);
      assert.equal(await page.locator('#queue button').count(),0,'terminal state controls removed');
      assert.match(await page.locator('#receipt-status').innerText(),/kein echter Treatwell-Termin/);
      await page.screenshot({path:path.join(output,`confirmed-${width}.png`),fullPage:true});
      await page.locator('#demo-role').selectOption('guest');
      assert.equal(await page.locator('#queue .queue-item').count(),0);
      assert.match(await page.locator('#team-message').innerText(),/keinen Zugriff/);
      await page.locator('#demo-role').selectOption('staff-demo');
      await page.locator('#customer').selectOption('demo-02');
      await page.locator('#booking-form button[type="submit"]').click();
      assert.equal(await page.locator('#queue .queue-item').count(),2);
      const second=page.locator('#queue .queue-item').first();
      await second.locator('input[name="treatwellReference"]').fill('DEMO-QA123');
      await second.locator('input[name="manuallyChecked"]').check();
      await second.locator('button[type="submit"]').click();
      assert.match(await second.locator('[role="alert"]').innerText(),/anderen Anfrage/);
      await page.locator('#queue .queue-item').first().getByRole('button',{name:'In der Demo ablehnen',exact:true}).click();
      assert.match(await page.locator('#queue .queue-item').first().innerText(),/DECLINED/);
      assert.equal(await page.locator('#queue .queue-item').first().locator('button').count(),0);
      await page.locator('.review-preview summary').click();
      const review = await page.locator('.review-preview').innerText();
      assert.match(review,/positiv, neutral oder kritisch/);
      assert.match(review,/Kein Versand/);
      assert.equal(await page.locator('.review-preview button,.review-preview a').count(),0);
      const storage=await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length,cookies:document.cookie}));
      assert.deepEqual(storage,{local:0,session:0,cookies:''});
      await context.setOffline(true);
      await page.locator('#reset-demo').click();
      assert.equal(await page.locator('#receipt').isVisible(),false);
      assert.equal(await page.locator('#demo-role').inputValue(),'guest');
      await page.locator('#demo-role').selectOption('staff-demo');
      assert.equal(await page.locator('#queue .queue-item').count(),0);
      await page.locator('#location').selectOption('demo-b');
      await page.locator('input[name="serviceId"][value="demo-colour"]').check();
      await page.locator('#date').fill(future);
      await page.locator('#time').fill('16:00');
      await page.locator('#booking-form input[name="privacyAccepted"]').check();
      await page.locator('#booking-form button[type="submit"]').click();
      assert.match(await page.locator('#receipt').innerText(),/PENDING/);
      assert.equal(await page.locator('#queue .queue-item').count(),1,'offline synthetic request works without network');
      await context.setOffline(false);
      await page.reload({waitUntil:'networkidle'});
      await page.locator('#demo-role').selectOption('staff-demo');
      assert.equal(await page.locator('#queue .queue-item').count(),0);
      assert.equal(await page.locator('#receipt').isVisible(),false);
      await page.goto(base,{waitUntil:'networkidle'});
      const keyboardTargets=[];
      for(let i=0;i<30;i++) {
        await page.keyboard.press('Tab');
        keyboardTargets.push(await page.evaluate(()=>({tag:document.activeElement.tagName,id:document.activeElement.id,name:document.activeElement.getAttribute('name'),text:document.activeElement.textContent.trim().slice(0,60)})));
      }
      for(const id of ['location','date','time','customer','demo-role','reset-demo']) assert.ok(keyboardTargets.some(t=>t.id===id),`keyboard reachability ${id}`);
      assert.ok(keyboardTargets.some(t=>t.name==='privacyAccepted'),'keyboard reachability privacy checkbox');
      assert.ok(keyboardTargets.some(t=>t.tag==='SUMMARY'),'keyboard reachability feedback disclosure');
      assert.equal(errors.length,0,'page errors');
      assert.equal(consoleErrors.length,0,`console errors: ${JSON.stringify(consoleErrors)}`);
      assert.ok(requests.every(r=>new URL(r.url).origin===base && r.method==='GET'),'outbound/non-GET request observed');
      results.push({width,result:'PASS',requests,errors,consoleErrors,storage,keyboardTargets});
      await context.close();
    }
    for (const [file,hash] of Object.entries(sources)) assert.equal(crypto.createHash('sha256').update(await fs.readFile(path.join(root,file))).digest('hex'),hash,`${file} changed during QA`);
    assert.equal(execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),testedCommit,'HEAD changed during QA');
    const evidence={time:new Date().toISOString(),commit:testedCommit,browser:await browser.version(),base,sources,results};
    await fs.writeFile(path.join(output,'browser-flow-results.json'),JSON.stringify(evidence,null,2));
    console.log(JSON.stringify(evidence,null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
